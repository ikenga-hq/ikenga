    #[test]
    fn check_scheduled_for_normalises_like_to_iso_string() {
        for (input, want) in [
            ("2099-11-03T09:00Z", "2099-11-03T09:00:00.000Z"),
            ("2099-11-03T10:00:00+01:00", "2099-11-03T09:00:00.000Z"),
            ("2099-11-03T09:00:00.123456789Z", "2099-11-03T09:00:00.123Z"),
            ("2099-11-03T09:00:00.9999Z", "2099-11-03T09:00:00.999Z"),
            (
                "2099-11-03T09:00:00.12345+05:30",
                "2099-11-03T03:30:00.123Z",
            ),
            ("2099-11-03T09:00:00.1Z", "2099-11-03T09:00:00.100Z"),
            ("2096-02-29T00:00:00-23:59", "2096-02-29T23:59:00.000Z"),
        ] {
            assert_eq!(
                check_scheduled_for(input, NOW).as_deref(),
                Ok(want),
                "{input}"
            );
        }
        for bad in [
            "2099-11-03 09:00:00Z",
            "2099-11-03T09:00:00",
            "2099-13-01T00:00:00Z",
            "2099-02-29T00:00:00Z",
            "2099-11-03T24:00:00Z",
            "2099-11-03T09:00:00+24:00",
            "2099-11-03T09:00:00.1234567890Z",
            "２０９９-11-03T09:00:00Z",
        ] {
            assert!(check_scheduled_for(bad, NOW).is_err(), "{bad}");
        }
    }

